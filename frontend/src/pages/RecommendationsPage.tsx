// frontend/src/pages/RecommendationsPage.tsx
import React, { useState, useEffect } from 'react';
import { 
  FileText, 
  Download, 
  CheckCircle2, 
  AlertCircle, 
  ExternalLink,
  ChevronRight,
  ShieldCheck,
  Building2
} from 'lucide-react';
import { Header } from '../components/Header';
import { ScientificNotice } from '../components/ScientificNotice';
import { useAuth } from '../context/AuthContext';
import { api, Assessment } from '../services/api';

export const RecommendationsPage: React.FC = () => {
  const { company } = useAuth();
  const [activeTab, setActiveTab] = useState<'executive' | 'technical' | 'recommendations'>('recommendations');
  const [rankings, setRankings] = useState<Assessment[]>([]);
  const [selectedAssessmentId, setSelectedAssessmentId] = useState<number | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    loadRankings();
  }, [company?.id]);

  const loadRankings = async () => {
    try {
      setLoading(true);
      const data = await api.getAssessmentRanking(company?.id);
      setRankings(data);
      if (data.length > 0 && !selectedAssessmentId) {
        setSelectedAssessmentId(data[0].id);
      }
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  const currentItem = rankings.find(r => r.id === selectedAssessmentId) || rankings[0];

  const [downloading, setDownloading] = useState<string | null>(null);
  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);

  const handleDownload = async (type: 'executive' | 'technical' | 'recommendations', label: string) => {
    if (!currentItem) return;
    try {
      setDownloading(label);
      setDownloadSuccess(null);
      await api.downloadReportPdf(type, currentItem.waste_stream_id);
      setDownloadSuccess(`${label} downloaded! Check your browser downloads.`);
      setTimeout(() => setDownloadSuccess(null), 5000);
    } catch (err: any) {
      alert(`Failed to generate report: ${err.message || err}`);
    } finally {
      setDownloading(null);
    }
  };

  return (
    <div className="flex-1 flex flex-col min-h-screen bg-[#F7F8F3] text-[#202C25]">
      <Header
        title="Reports & Recommendations"
        subtitle="Generate detailed reports with insights and next steps."
      />

      <div className="max-w-[1360px] w-full mx-auto px-6 md:px-8 py-6 space-y-6">
        
        <ScientificNotice>
          <p>
            <strong>Statutory Environmental Advisory:</strong> Recommendations generated by IndusTrace AI reflect engineering decision-support heuristics. They do not constitute statutory environmental pollution control board clearances or authorized transport permits.
          </p>
        </ScientificNotice>

        {/* Tab Switcher matching Reference Panel 10 */}
        <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-4">
          <div className="flex items-center bg-[#E5EEE3] p-1.5 rounded-xl border border-[#DCE5DA]">
            <button
              onClick={() => setActiveTab('executive')}
              className={`px-5 py-2 rounded-lg text-[14px] font-semibold transition ${
                activeTab === 'executive'
                  ? 'bg-[#FFFFFF] text-[#202C25] shadow-2xs border border-[#DCE5DA]'
                  : 'text-[#56645A] hover:text-[#202C25]'
              }`}
            >
              Executive Summary
            </button>
            <button
              onClick={() => setActiveTab('technical')}
              className={`px-5 py-2 rounded-lg text-[14px] font-semibold transition ${
                activeTab === 'technical'
                  ? 'bg-[#FFFFFF] text-[#202C25] shadow-2xs border border-[#DCE5DA]'
                  : 'text-[#56645A] hover:text-[#202C25]'
              }`}
            >
              Technical Report
            </button>
            <button
              onClick={() => setActiveTab('recommendations')}
              className={`px-5 py-2 rounded-lg text-[14px] font-semibold transition ${
                activeTab === 'recommendations'
                  ? 'bg-[#FFFFFF] text-[#202C25] shadow-2xs border border-[#DCE5DA]'
                  : 'text-[#56645A] hover:text-[#202C25]'
              }`}
            >
              Recommendations
            </button>
          </div>

          {/* Stream selector */}
          <div className="flex items-center gap-2">
            <span className="text-[13px] font-medium text-[#778279]">Stream:</span>
            <select
              value={selectedAssessmentId || ''}
              onChange={(e) => setSelectedAssessmentId(parseInt(e.target.value))}
              className="px-3.5 py-2 rounded-xl border border-[#DCE5DA] bg-[#FFFFFF] text-[#202C25] text-[14px] font-semibold focus:outline-none focus:ring-2 focus:ring-[#278653]"
            >
              {rankings.map(r => (
                <option key={r.id} value={r.id}>{r.stream_name} (TWS: {r.tws_score})</option>
              ))}
            </select>
          </div>
        </div>

        {currentItem && (
          <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
            
            {/* Left Content Area matching Reference Panel 10 */}
            <div className="lg:col-span-8 bg-[#FFFFFF] p-8 rounded-3xl border border-[#DCE5DA] shadow-2xs space-y-8">
              
              {/* Header section */}
              <div>
                <div className="flex items-center gap-2 text-[#26734D] text-[13px] font-bold uppercase tracking-wider">
                  <span>Stream Assessment Dossier</span>
                  <span>•</span>
                  <span>Priority Level: {currentItem.priority_level}</span>
                </div>
                <h3 className="text-[26px] font-bold text-[#202C25] mt-1">
                  {currentItem.stream_name}
                </h3>
                <p className="text-[14px] text-[#56645A] mt-1">
                  Company Facility: <strong>{company?.name || currentItem.company_name}</strong> • TWS Score: <strong>{currentItem.tws_score}/100</strong>
                </p>
              </div>

              {/* Key Findings matching Reference Panel 10 numbered pills */}
              <div className="space-y-3.5">
                <h4 className="font-bold text-[18px] text-[#202C25]">Key Findings</h4>
                
                <div className="space-y-3 text-[14px] text-[#56645A]">
                  <div className="flex items-start gap-3 p-3.5 rounded-xl bg-[#F0F5EC]">
                    <div className="w-6 h-6 rounded-full bg-[#278653] text-white flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">
                      1
                    </div>
                    <p className="leading-relaxed">
                      <strong>Elevated Test Worthiness:</strong> Stream has an overall TWS Priority score of {currentItem.tws_score}/100 requiring characterization.
                    </p>
                  </div>

                  <div className="flex items-start gap-3 p-3.5 rounded-xl bg-[#F0F5EC]">
                    <div className="w-6 h-6 rounded-full bg-[#278653] text-white flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">
                      2
                    </div>
                    <p className="leading-relaxed">
                      <strong>Critical Information Gaps:</strong> {currentItem.missing_critical_info.length > 0 ? currentItem.missing_critical_info.join(', ') : 'Trace contaminant profiles and certified alloy boundaries are pending.'}
                    </p>
                  </div>

                  <div className="flex items-start gap-3 p-3.5 rounded-xl bg-[#F0F5EC]">
                    <div className="w-6 h-6 rounded-full bg-[#278653] text-white flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">
                      3
                    </div>
                    <p className="leading-relaxed">
                      <strong>Secondary Matrix Value:</strong> Moderate to high potential for non-ferrous metal recovery or in-house briquetting once coolant contamination is quantified.
                    </p>
                  </div>

                  <div className="flex items-start gap-3 p-3.5 rounded-xl bg-[#F0F5EC]">
                    <div className="w-6 h-6 rounded-full bg-[#278653] text-white flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">
                      4
                    </div>
                    <p className="leading-relaxed">
                      <strong>Recommended Pathway:</strong> {currentItem.recommendation} — {currentItem.recommendation_details.reason}
                    </p>
                  </div>
                </div>
              </div>

              {/* Recommended Next Steps matching Reference Panel 10 */}
              <div className="space-y-3.5 pt-4 border-t border-[#DCE5DA]">
                <h4 className="font-bold text-[18px] text-[#202C25]">Recommended Next Steps</h4>

                <div className="space-y-2.5 text-[14px]">
                  <div className="flex items-center gap-3 p-3 rounded-xl border border-[#DCE5DA] hover:bg-[#F7F8F3] transition">
                    <CheckCircle2 className="w-5 h-5 text-[#26734D] flex-shrink-0" />
                    <span>Conduct certified ICP-OES laboratory assay for base alloy composition.</span>
                  </div>
                  <div className="flex items-center gap-3 p-3 rounded-xl border border-[#DCE5DA] hover:bg-[#F7F8F3] transition">
                    <CheckCircle2 className="w-5 h-5 text-[#26734D] flex-shrink-0" />
                    <span>Analyze coolant residual moisture to determine drying requirements.</span>
                  </div>
                  <div className="flex items-center gap-3 p-3 rounded-xl border border-[#DCE5DA] hover:bg-[#F7F8F3] transition">
                    <CheckCircle2 className="w-5 h-5 text-[#26734D] flex-shrink-0" />
                    <span>Evaluate briquetting vs direct furnace remelt using verified fractions.</span>
                  </div>
                  <div className="flex items-center gap-3 p-3 rounded-xl border border-[#DCE5DA] hover:bg-[#F7F8F3] transition">
                    <CheckCircle2 className="w-5 h-5 text-[#26734D] flex-shrink-0" />
                    <span>Perform economic mass-balance analysis with real supplier haulage quotes.</span>
                  </div>
                </div>
              </div>

            </div>

            {/* Right: Photographic Card & Export Center matching Panel 10 */}
            <div className="lg:col-span-4 space-y-6">
              
              {/* Sustainability Leaf Image Card with Download Overlay */}
              <div className="relative rounded-3xl overflow-hidden border border-[#DCE5DA] shadow-md bg-[#10271E] h-[480px]">
                <img
                  src="/images/leaf-plant.jpg"
                  alt="Download Report"
                  className="w-full h-full object-cover opacity-80"
                />
                <div className="absolute inset-0 bg-gradient-to-t from-[#10271E]/90 via-[#10271E]/40 to-transparent"></div>

                <div className="absolute inset-x-6 bottom-6 p-6 rounded-2xl bg-[#FFFFFF]/95 backdrop-blur-md border border-[#DCE5DA] shadow-lg space-y-3">
                  <div className="flex items-center justify-between text-[#26734D] font-bold text-[15px]">
                    <div className="flex items-center gap-2">
                      <Download className="w-4.5 h-4.5" />
                      <span>Download Report</span>
                    </div>
                    {downloading && (
                      <span className="text-[11px] font-normal text-[#56645A] animate-pulse">Generating...</span>
                    )}
                  </div>

                  {downloadSuccess && (
                    <div className="p-2 rounded-lg bg-[#E5EEE3] text-[#1B4D36] text-[12px] font-medium border border-[#DCE5DA]">
                      ✓ {downloadSuccess}
                    </div>
                  )}

                  <div className="space-y-2 pt-1">
                    <button
                      onClick={() => handleDownload('executive', 'Executive Summary')}
                      disabled={!!downloading}
                      className="w-full py-2.5 px-3 rounded-xl bg-[#F0F5EC] hover:bg-[#E5EEE3] text-[#202C25] font-semibold text-[13px] text-left flex items-center justify-between transition disabled:opacity-60"
                    >
                      <span>Executive Summary (PDF)</span>
                      <Download className="w-3.5 h-3.5 text-[#26734D]" />
                    </button>
                    <button
                      onClick={() => handleDownload('technical', 'Technical Report')}
                      disabled={!!downloading}
                      className="w-full py-2.5 px-3 rounded-xl bg-[#F0F5EC] hover:bg-[#E5EEE3] text-[#202C25] font-semibold text-[13px] text-left flex items-center justify-between transition disabled:opacity-60"
                    >
                      <span>Technical Report (PDF)</span>
                      <Download className="w-3.5 h-3.5 text-[#26734D]" />
                    </button>
                    <button
                      onClick={() => handleDownload('recommendations', 'Recommendations')}
                      disabled={!!downloading}
                      className="w-full py-2.5 px-3 rounded-xl bg-[#F0F5EC] hover:bg-[#E5EEE3] text-[#202C25] font-semibold text-[13px] text-left flex items-center justify-between transition disabled:opacity-60"
                    >
                      <span>Recommendations (PDF)</span>
                      <Download className="w-3.5 h-3.5 text-[#26734D]" />
                    </button>
                  </div>
                </div>
              </div>

            </div>

          </div>
        )}

      </div>
    </div>
  );
};
